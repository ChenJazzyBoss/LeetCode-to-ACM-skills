  const enumValues = allText.match(/[A-Z]{2,}/g) ?? [];
  const chineseValues = allText.match(/[^，。、\s]{2,}(?=[、]|(?:和|及))/g) ?? [];
  const allValues = [.../* @__PURE__ */ new Set([...enumValues, ...chineseValues])];
